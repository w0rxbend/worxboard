"""Generate worxboard-layouts.dtsi (ZMK physical layout + matrix transform) from layout.json.

    python3 firmware/zmk/scripts/gen_layouts.py            # write the dtsi
    python3 firmware/zmk/scripts/gen_layouts.py --check    # exit 1 if the committed dtsi is stale

Reads only the WS0 contract layout/build/layout.json (stdlib, no venv needed).
Units: 100 = 1u = 19.05 mm. Keys are emitted in transform order (§5 order rule), so the
keymap, the transform and the physical layout share one index. Thumbs rotate about their
own centres; ZMK rotation is clockwise-positive, the layout frame is CCW-positive.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LAYOUT_JSON = ROOT / "layout/build/layout.json"
OUT = ROOT / "firmware/zmk/boards/worxbend/worxboard/worxboard-layouts.dtsi"

UNIT = 100               # ZMK physical-layout units per key pitch
SPLIT_GAP = 100          # right half placed this far (1u) right of the left half's bounds
ROWS, COLS = 6, 14
LINE_SIZES = (12, 14, 12, 14, 10, 4, 2, 6)   # transform lines: 5 key rows, 3 thumb rows


def _corners(cx, cy, w, h, rot_cw):
    """Corners of a w x h key centred at (cx, cy) rotated rot_cw degrees clockwise (y down)."""
    a = math.radians(rot_cw)
    c, s = math.cos(a), math.sin(a)
    for dx, dy in ((-w, -h), (w, -h), (w, h), (-w, h)):
        dx, dy = dx / 2, dy / 2
        yield cx + dx * c - dy * s, cy + dx * s + dy * c


def _keys(data):
    """[(side, key dict, centre_x, centre_y, w, h, rot_cw)] in transform order, in units."""
    scale = UNIT / data["pitch"]
    by_id = {s: {k["id"]: k for k in v["keys"]} for s, v in data["sides"].items()}
    out = []
    for t in data["transform_order"]:
        k = by_id[t["side"]][t["id"]]
        assert k["rc"] == t["rc"], (t, k["rc"])
        out.append((t["side"], k, k["x"] * scale, k["y"] * scale,
                    k["w"] * UNIT, k["h"] * UNIT, -k["rot"]))
    return out


def _bounds(keys, side):
    pts = [p for s, _, cx, cy, w, h, r in keys if s == side for p in _corners(cx, cy, w, h, r)]
    return min(p[0] for p in pts), max(p[0] for p in pts), min(p[1] for p in pts)


def _cell(v: int) -> str:
    return f"({v})" if v < 0 else str(v)


def render(data) -> str:
    keys = _keys(data)
    assert len(keys) == 74, len(keys)
    lmin, lmax, lymin = _bounds(keys, "left")
    rmin, _, rymin = _bounds(keys, "right")
    dx = {"left": -lmin, "right": (lmax - lmin) + SPLIT_GAP - rmin}
    dy = -min(lymin, rymin)

    rows = []
    for i, (side, k, cx, cy, w, h, rot) in enumerate(keys):
        cx, cy = cx + dx[side], cy + dy
        x, y = round(cx - w / 2), round(cy - h / 2)
        r = round(rot * 100)
        rx, ry = (round(cx), round(cy)) if r else (0, 0)
        cells = f"{round(w):3d} {round(h):3d} {x:4d} {y:4d} {_cell(r):>7} {rx:4d} {ry:4d}"
        lead = "=" if i == 0 else ","
        legend = k["legend"].replace("\\", "BSLS")   # a trailing '\' would splice the next line
        rows.append(f"            {lead} <&key_physical_attrs {cells}>  "
                    f"// {i:2d} {side[0].upper()} {k['id']:<4} {legend}")

    rcs = [f"RC({r},{c})" for _, k, *_ in keys for r, c in [k["rc"]]]
    lines, i = [], 0
    for n in LINE_SIZES:
        lines.append("            " + " ".join(f"{rc:<8}" for rc in rcs[i:i + n]).rstrip())
        i += n
    assert i == len(rcs)

    return "\n".join([
        "/* SPDX-License-Identifier: MIT */",
        "/* GENERATED by firmware/zmk/scripts/gen_layouts.py from layout/build/layout.json.",
        " * Do not edit: run `just fw-layouts`. 74 keys in transform order (design.md §5);",
        " * 100 = 19.05 mm. R0C6 (left) and R0C7 (right) are the displays and are not mapped. */",
        "#include <physical_layouts.dtsi>",
        "#include <dt-bindings/zmk/matrix_transform.h>",
        "",
        "/ {",
        "    default_transform: keymap_transform_0 {",
        '        compatible = "zmk,matrix-transform";',
        f"        columns = <{COLS}>;",
        f"        rows = <{ROWS}>;",
        "        map = <",
        *lines,
        "        >;",
        "    };",
        "",
        "    worxboard_layout: worxboard_layout {",
        '        compatible = "zmk,physical-layout";',
        '        display-name = "worxboard";',
        "        transform = <&default_transform>;",
        "",
        "        keys  //                     w   h    x    y     rot   rx   ry",
        *rows,
        "            ;",
        "    };",
        "};",
        "",
    ])


def main(argv: list[str]) -> int:
    text = render(json.loads(LAYOUT_JSON.read_text()))
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run `just fw-layouts`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
