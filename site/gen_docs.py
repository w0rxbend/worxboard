"""Generate the docs tables from the design sources.

- docs/pinout.md and docs/matrix.md, whole files: layout/build/layout.json, plus the part references
  of pcb/scripts/design.py and the placements of the committed pcb/<side>/worxboard-<side>.kicad_pcb.
- docs/bom.md, the blocks between the GENERATED markers: the JLC BOM per half and the parts kept out
  of it, from pcb/scripts/design.py, checked against both committed boards.

    python site/gen_docs.py            # write the files
    python site/gen_docs.py --check    # exit 1 if a committed file is stale
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

import pcbdata as PCB

ROOT = Path(__file__).resolve().parent.parent
LAYOUT_JSON = ROOT / "layout/build/layout.json"
PINOUT_MD = ROOT / "docs/pinout.md"
MATRIX_MD = ROOT / "docs/matrix.md"
BOM_MD = ROOT / "docs/bom.md"

ROWS, COLS = 6, 7            # per half
GLOBAL_COLS = 14             # ZMK transform: left 0..6, right 7..13
DISPLAY_RC = (0, 6)          # physical slot replaced by the LCD on both halves
SIDES = ("left", "right")
BANNER = ("<!-- GENERATED by site/gen_docs.py from layout/build/layout.json, pcb/scripts/design.py and "
          "pcb/<side>/worxboard-<side>.kicad_pcb. Do not edit: run `just docs-gen`. -->")
BLOCK = re.compile(r"(<!-- BEGIN GENERATED: (\w+) .*?-->\n).*?(<!-- END GENERATED: \2 -->)", re.S)

# LCSC number -> (part, status flag of spec §7, JLC extended part). The flags are hand-kept: [C] verified
