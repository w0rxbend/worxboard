# Parts kept out of the JLC BOM/CPL (reference prefix -> what it is, why)
NOT_ASSEMBLED = {
    "JP1": ("solder jumper VSYS → F1 → VLINK, bridged", "copper only; cut it for split-powered mode"),
    "TP": ("Ø1.0 mm test pads", "copper only"),
    "H": ("M2.5 mounting holes, NPTH Ø2.7", "drilled"),
    "STAB_": ("2u stabiliser holes (board-only footprint, no symbol)", "drilled"),
}
MAX_NETS = 8                 # a part with more nets links to the pin table instead


def _mm(v: float, nd: int = 3) -> str:
    return f"{v:.{nd}f}".rstrip("0").rstrip(".")


def _xy(p) -> str:
    return f"({_mm(p[0])}, {_mm(p[1])})"


def _code(s: str) -> str:
    """Inline code that survives backticks (`` `LT(1,`)` `` etc.) and table pipes."""
    s = s.replace("|", "\\|")
    return f"`` {s} ``" if "`" in s else f"`{s}`"


def _table(head: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _pos(f) -> str:
    return f"({_mm(f.x, 2)}, {_mm(f.y, 2)}) {_mm(f.rot, 1)}°"


def _nets(part) -> list[str]:
    return sorted({n for n in part.pins.values() if n})


def _gpio_no(name: str) -> int | None:
    return int(name[4:].split("/")[0]) if name.startswith("GPIO") else None


# ---------------------------------------------------------------- pinout.md
def pinout(d: dict) -> str:
    p = d["pins"]
    gp = {g["net"]: g for g in p["gpio"] if g["net"]}
    out = [BANNER, "", "# Pinout", "",
           "The RP2040 GPIO map is identical on both PCBs (spec §3, `layout/pins.py`). "
           "Symbol pin **names** are the authority; QFN pin numbers are informational. "
           "Electrical context is in [electrical.md](electrical.md), the key matrix in [matrix.md](matrix.md).", "",
           "## RP2040 pins", ""]
    rows = [[f"`{g['name']}`", str(g["qfn"]), f"`{g['net']}`" if g["net"] else "n/c", g["note"] or ""]
            for g in p["gpio"]]
    out += _table(["Pin", "QFN", "Net", "Notes"], rows)

    out += ["", "## Matrix GPIOs", "",
            "Rows are inputs with an internal pull-down; columns are outputs (`col2row`). "
            "Both PCBs use the same nets. The right half's `.dts` lists the column GPIOs in reverse, "
            "so its logical column 0 is the inner column, and `col-offset = <7>` puts it at global column 7.", ""]
    rows = [[f"`ROW{i}`", f"GP{g}", str(gp[f"ROW{i}"]["qfn"])] for i, g in enumerate(p["rows"])]
    out += _table(["Row net", "GPIO", "QFN"], rows)
    out += [""]
    rows = []
    for i, g in enumerate(p["cols"]):
        r = p["right_cols"].index(g)
        rows.append([f"`COL{i}`", f"C{i}" + (" (outer)" if i == 0 else " (inner)" if i == COLS - 1 else ""),
                     f"GP{g}", str(i), str(i), str(r), str(r + COLS)])
    out += _table(["Col net", "Physical column", "GPIO", "Left logical", "Left global",
                   "Right logical", "Right global"], rows)

    u = p["uart"]
    out += ["", "## TRRS (split link)", "",
            f"UART0, GP{u['tx']} TX and GP{u['rx']} RX at {u['baud']} baud, ZMK `zmk,wired-split`. "
            "Use a **straight** 4-pole cable: the TX/RX crossover is in the PCB netlist, so the firmware "
            "pinctrl is the same on both halves. **Never plug or unplug the TRRS cable while either half is powered.**", ""]
    contacts = (("T", "Tip"), ("R1", "Ring1"), ("R2", "Ring2"), ("S", "Sleeve"))
    rows = []
    for key, label in contacts:
        cells = [label]
        for s in SIDES:
            net = p["trrs"][s][key]
            sig = p["trrs"][s].get(net)
            cells.append(f"`{net}` = **{sig}**" if sig else f"`{net}`")
        rows.append(cells)
    out += _table(["Contact", "Left PCB", "Right PCB"], rows)

    disp = d["sides"]["right"]["display"]
    order = d["display_part"]["header_pin_order"]
    net_of = {"MOSI": "DISP_MOSI", "SCK": "DISP_SCK", "VCC": "3V3", "GND": "GND", "CS": "DISP_CS"}
    out += ["", "## Display header J3", "",
            "1×5 2.54 mm female socket, 5.0 mm tall (C27985230), fitted by JLC as a through-hole part. Pin *n* "
            "is nice!view pin *n*. Pin 1 (MOSI) is at **high x** in each half's own frame: the **outer** end of "
            "the socket on the right half and the **inner** end on the left, because the module is one part "
            "mounted LCD up the same way on both halves, header at the back (deviation BOARD-1). "
            "`netcmp.py --board` stops stages C and D if J3 is turned the wrong way (deviation ELEC-8; "
            "[verification.md](verification.md#g1-niceview-display)).", ""]
    rows = []
    for i, (fn, xy) in enumerate(zip(order, disp["header_pins"]), 1):
        net = net_of[fn]
        no = _gpio_no(gp[net]["name"]) if net in gp else None
        g = f"GP{no}" if no is not None else "—"
        left = d["sides"]["left"]["display"]["header_pins"][i - 1]
        rows.append([str(i), fn, f"`{net}`", g, _xy(xy), _xy(left)])
    out += _table(["Pin", "Function", "Net", "GPIO", "Right frame (mm)", "Left frame (mm)"], rows)

    out += ["", "## Part positions", "",
            "Footprint origins as placed in the committed boards (`pcb/<side>/worxboard-<side>.kicad_pcb`), "
            "KiCad frame of each half in mm (+y towards the user). The left half is the mirror image "
            f"(x_L = {_mm(d['mirror_x'])} − x_R) except where the board needed otherwise: the left RP2040 and "
            "flash are turned 180° and moved (deviations WS2b-1, WS2b-2), so the passives around them differ too. "
            "All of these parts are on the top side. Key sockets and diodes are listed in "
            "[matrix.md](matrix.md#sockets-and-diodes).", ""]
    fl, fr = PCB.footprints("left"), PCB.footprints("right")
    dl = {p.ref: p for p in PCB.design("left")}
    dr = {p.ref: p for p in PCB.design("right")}
    rows = []
    for ref in sorted(dl, key=PCB.ref_key):
        if dl[ref].group == "MATRIX":
            continue
        nl, nr = _nets(dl[ref]), _nets(dr[ref])
        if len(nl) > MAX_NETS:
            nets = "[RP2040 pins](#rp2040-pins)"
        elif nl == nr:
            nets = ", ".join(f"`{n}`" for n in nl)
        else:
            nets = "left " + ", ".join(f"`{n}`" for n in nl) + "; right " + ", ".join(f"`{n}`" for n in nr)
        rows.append([f"`{ref}`", dl[ref].value, nets, _pos(fl[ref]), _pos(fr[ref])])
    out += _table(["Ref", "Value", "Nets", "Left (x, y) rot", "Right (x, y) rot"], rows)

    out += ["", "## Mounting holes", "",
            f"M2.5 NPTH Ø{_mm(d['hole']['drill'])}, copper and component keepout Ø{_mm(d['hole']['keepout'])}. "
            "Hole 7 moved from the stock ErgoDox position to make room for the display.", ""]
    hl, hr = d["sides"]["left"]["holes"], d["sides"]["right"]["holes"]
    rows = [[str(i), f"`H{i + 1}`", _xy(a), _xy(b)] for i, (a, b) in enumerate(zip(hl, hr))]
    out += _table(["#", "PCB ref", "Left", "Right"], rows)
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- matrix.md
def _grid(keys: list[dict]) -> dict[tuple[int, int], dict]:
    return {(k["row"], k["col"]): k for k in keys}


def matrix(d: dict) -> str:
    p = d["pins"]
    out = [BANNER, "", "# Key matrix", "",
           "Each half has a 6 × 7 diode matrix, `col2row`: the diode anode is on the switch/column side and "
           "the cathode on the ROW net. Diodes are 1N4148W (SOD-123) on the bottom side next to each "
           "hot-swap socket. Both PCBs share **one** matrix netlist: `COLn` is physical column Cn "
           "(C0 outer, C6 inner) on both halves.", "",
           f"- Keys per half: **{len(d['sides']['left']['keys'])}**, total "
           f"**{sum(len(d['sides'][s]['keys']) for s in SIDES)}**.",
           f"- Slot (R{DISPLAY_RC[0]}, C{DISPLAY_RC[1]}) is the display on both halves and is not mapped.",
           "- Legends are the ZMK base layer (QMK `ergodox_ez` layer 0; LEFT/RGHT moved to layer 1).", ""]

    for s in SIDES:
        g = _grid(d["sides"][s]["keys"])
        out += [f"## {s.capitalize()} half (physical)", "",
                "Cells show the key id, its legend and the global ZMK position `RC(row, col)`.", ""]
        head = ["Row \\ Col"] + [f"`COL{c}` GP{p['cols'][c]}" for c in range(COLS)]
        rows = []
        for r in range(ROWS):
            cells = [f"`ROW{r}` GP{p['rows'][r]}"]
            for c in range(COLS):
                k = g.get((r, c))
                if k:
                    cells.append(f"{k['id']} {_code(k['legend'])} ({k['rc'][0]},{k['rc'][1]})")
                else:
                    cells.append("**DISPLAY**" if (r, c) == DISPLAY_RC else "—")
            rows.append(cells)
        out += _table(head, rows) + [""]

    out += ["## ZMK transform (6 × 14)", "",
            "The global map the keymap and ZMK Studio see. Left columns 0–6 are physical C0–C6; right columns "
            "7–13 are physical C6–C0 (the right `.dts` reverses `col-gpios` and sets `col-offset = <7>`).", ""]
    glob = {}
    for s in SIDES:
        for k in d["sides"][s]["keys"]:
            glob[tuple(k["rc"])] = (s, k)
    head = ["Row"] + [str(c) for c in range(GLOBAL_COLS)]
    rows = []
    for r in range(ROWS):
        cells = [str(r)]
        for c in range(GLOBAL_COLS):
            if (r, c) in glob:
                cells.append(_code(glob[(r, c)][1]["legend"]))
            else:
                disp = (r == DISPLAY_RC[0] and c in (DISPLAY_RC[1], GLOBAL_COLS - 1 - DISPLAY_RC[1]))
                cells.append("LCD" if disp else "·")
        rows.append(cells)
    out += _table(head, rows) + [""]

    out += ["## Sockets and diodes", "",
            "Each key has a Kailh hot-swap socket `SK` and a diode `D` on the bottom side, numbered from 101 in "
            "`layout` key order (deviation WS2a-1). The references are the same on both PCBs; the diode anode is on "
            "the switch net `MX_<key>`, the cathode on the row.", ""]
    keys_l = {k["id"]: k for k in d["sides"]["left"]["keys"]}
    keys_r = {k["id"]: k for k in d["sides"]["right"]["keys"]}
    parts = PCB.design("left")
    sockets = {p.key: p for p in parts if p.ref.startswith("SK")}
    diodes = {p.key: p for p in parts if p.group == "MATRIX" and p.ref.startswith("D")}
    rows = []
    for kid, sk in sockets.items():
        kl = keys_l[kid]
        rows.append([kid, f"`{sk.ref}`", f"`{diodes[kid].ref}`", f"`ROW{kl['row']}`", f"`COL{kl['col']}`",
                     _code(kl["legend"]), _code(keys_r[kid]["legend"])])
    out += _table(["Key", "Socket", "Diode", "Row", "Column", "Left legend", "Right legend"], rows) + [""]

    out += ["## Keymap order", "",
            "Bindings in `worxboard.keymap`, the transform `map` and the physical layout all follow this order "
            "(12 / 14 / 12 / 14 / 10, then the thumbs).", ""]
    keys = {(s, k["id"]): k for s in SIDES for k in d["sides"][s]["keys"]}
    rows = []
    for i, t in enumerate(d["transform_order"]):
        k = keys[(t["side"], t["id"])]
        rows.append([str(i), t["side"], t["id"], f"RC({t['rc'][0]},{t['rc'][1]})", _code(k["legend"]),
                     _mm(k["x"], 4), _mm(k["y"], 4), _mm(k["rot"]), f"{_mm(k['w'])}×{_mm(k['h'])}"])
    out += _table(["#", "Half", "Key", "Position", "Legend", "x (mm)", "y (mm)", "rot (°)", "Size (u)"], rows)
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- bom.md blocks
def _bottom_refs(refs: list[str]) -> list[str]:
    """The references assembled on the bottom side; each sits on the same side of both boards."""
    left, right = (PCB.footprints(s) for s in SIDES)
    differ = [r for r in refs if left[r].side != right[r].side]
    if differ:
        raise SystemExit(f"bom: {differ} sit on different sides of the two boards")
    return [r for r in refs if left[r].side == "bottom"]


def _side_cell(total: int, bottom: int) -> str:
    """`top`, `**bottom**`, or both with counts when one BOM line has parts on both sides."""
    if bottom == 0:
        return "top"
    return "**bottom**" if bottom == total else f"top {total - bottom}, **bottom** {bottom}"


def _check_boards() -> None:
    """Every design part is on both boards with its value and footprint (the docs follow the boards)."""
    for s in SIDES:
        fps = PCB.footprints(s)
        for p in PCB.design(s):
            f = fps.get(p.ref)
            if f is None or (f.value, f.lib) != (p.value, p.footprint):
                raise SystemExit(f"bom: {s} {p.ref} differs between design.py and the board: {f}")


def _refs(refs: list[str]) -> str:
    """References with runs of three or more collapsed: C5, C8–C17."""
    out, run = [], []
    for r in sorted(refs, key=PCB.ref_key) + [None]:
        k = PCB.ref_key(r) if r else None
        if run and k and k[0] == PCB.ref_key(run[-1])[0] and k[1] == PCB.ref_key(run[-1])[1] + 1:
            run.append(r)
            continue
        if run:
            out += [f"{run[0]}–{run[-1]}"] if len(run) >= 3 else run
        run = [r] if r else []
    return ", ".join(out)


def bom_assembled() -> list[str]:
    _check_boards()
    groups: dict[tuple[str, str, str], list[str]] = {}
    for p in PCB.design("left"):
        if p.in_bom and not p.dnp:
            groups.setdefault((p.value, p.footprint, p.lcsc), []).append(p.ref)
    shared = {lcsc for lcsc, n in Counter(k[2] for k in groups).items() if n > 1}
    rows, bottom_total = [], 0
    for (value, fp, lcsc), refs in groups.items():
        what, flag, ext = LCSC[lcsc]
        what += f" ({value})" if lcsc in shared else ""     # SW1 BOOT / SW2 RESET: one part, two lines
        bottom = len(_bottom_refs(refs))
        bottom_total += bottom
        rows.append([_refs(refs), str(len(refs)), what, f"[{lcsc}](https://jlcpcb.com/partdetail/{lcsc})",
                     f"`{fp.split(':')[1]}`", _side_cell(len(refs), bottom), flag, "yes" if ext else ""])
    n = sum(int(r[1]) for r in rows)
    out = _table(["Designators", "Qty", "Part", "LCSC", "Footprint", "Side", "Status", "Extended"], rows)
    return out + ["", f"{len(rows)} BOM lines, {n} parts per half, {bottom_total} of them on the bottom side."]


def bom_excluded(d: dict) -> list[str]:
    fps = PCB.footprints("left")
    nets = {p.ref: p.value for p in PCB.design("left")}
    gpio = {g["net"]: f"GP{_gpio_no(g['name'])}" for g in d["pins"]["gpio"] if g["net"] and g["name"].startswith("GPIO")}
    rows = []
    for prefix, (what, why) in NOT_ASSEMBLED.items():
        refs = sorted((r for r in fps if r.startswith(prefix)), key=PCB.ref_key)
        if prefix == "TP":                      # test pads are named after their net (spares: TPn = GPn)
            what += ": " + ", ".join(f"{r} {gpio[nets[r]] if nets[r] == r else f'`{nets[r]}`'}" for r in refs)
        rows.append([_refs(refs), str(len(refs)), what, why])
    return _table(["Designators", "Qty", "What", "Why"], rows)


def bom(d: dict, text: str) -> str:
    blocks = {"bom_assembled": bom_assembled, "bom_excluded": lambda: bom_excluded(d)}
    found = set()

    def fill(m: re.Match) -> str:
        found.add(m.group(2))
        return m.group(1) + "\n".join(blocks[m.group(2)]()) + "\n" + m.group(3)

    text = BLOCK.sub(fill, text)
    if found != set(blocks):
        raise SystemExit(f"bom.md: GENERATED blocks missing: {sorted(set(blocks) - found)}")
    return text


def outputs() -> dict[Path, str]:
    d = json.loads(LAYOUT_JSON.read_text())
    return {PINOUT_MD: pinout(d), MATRIX_MD: matrix(d), BOM_MD: bom(d, BOM_MD.read_text())}


def main(argv: list[str]) -> int:
    files = outputs()
    if "--check" in argv:
        stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run `just docs-gen`)", file=sys.stderr)
        return 1 if stale else 0
    for p, text in files.items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
